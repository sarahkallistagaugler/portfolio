const SITE_GATE_PASSWORD = "fyhcod-5Bybsa-wyrvam";
const SITE_GATE_STORAGE_KEY = "skg-portfolio-access";

const gridMap = {
  interactive: document.querySelector("#interactive-grid"),
  emails: document.querySelector("#emails-grid"),
  layout: document.querySelector("#layout-grid"),
};

const siteGateEl = document.querySelector("#site-gate");
const siteGateFormEl = document.querySelector("#site-gate-form");
const siteGatePasswordEl = document.querySelector("#site-gate-password");
const siteGateErrorEl = document.querySelector("#site-gate-error");
const modalEl = document.querySelector("#project-modal");
const modalImageEl = document.querySelector("#modal-image");
const modalKickerEl = document.querySelector("#modal-kicker");
const modalTitleEl = document.querySelector("#modal-title");
const modalBodyEl = document.querySelector("#modal-body");
const modalSecondaryMediaEl = document.querySelector("#modal-secondary-media");
const modalPrevEl = document.querySelector("#modal-prev");
const modalNextEl = document.querySelector("#modal-next");
const modalCloseEl = document.querySelector("#modal-close");
const topNavEl = document.querySelector("#top-nav");
const heroEl = document.querySelector("#home");
const menuToggleEl = document.querySelector("#menu-toggle");
const siteNavEl = document.querySelector("#site-nav");

const modalState = {
  section: null,
  projectIndex: 0,
  isSwitching: false,
};

function unlockSite(remember = true) {
  if (remember) {
    localStorage.setItem(SITE_GATE_STORAGE_KEY, "granted");
  }

  document.body.classList.remove("site-locked");
  document.body.classList.add("site-unlocked");
  siteGateEl.classList.add("is-hidden");
}

function setupSiteGate() {
  if (!siteGateEl || !siteGateFormEl || !siteGatePasswordEl || !siteGateErrorEl) return;

  if (localStorage.getItem(SITE_GATE_STORAGE_KEY) === "granted") {
    unlockSite(false);
    return;
  }

  siteGatePasswordEl.focus();

  siteGateFormEl.addEventListener("submit", (event) => {
    event.preventDefault();
    const submittedPassword = siteGatePasswordEl.value;

    if (submittedPassword === SITE_GATE_PASSWORD) {
      siteGateErrorEl.textContent = "";
      unlockSite();
      return;
    }

    siteGateErrorEl.textContent = "Incorrect password.";
    siteGatePasswordEl.select();
  });
}

function renderCards() {
  Object.entries(gridMap).forEach(([section, container]) => {
    if (!container) return;

    container.innerHTML = portfolioData[section]
      .map(
        (project, index) => `
          <article
            class="project-card"
            tabindex="0"
            data-project-trigger="true"
            data-section="${section}"
            data-index="${index}"
            aria-label="Open project: ${project.title}"
          >
            <img class="project-card__media" src="${project.media[0]}" alt="${project.title} preview image" loading="lazy" />
          </article>
        `
      )
      .join("");
  });
}

function renderModal() {
  const project = portfolioData[modalState.section][modalState.projectIndex];
  const [primaryMedia, ...secondaryMedia] = project.media;

  modalImageEl.src = primaryMedia;
  modalImageEl.alt = `${project.title} primary image`;
  modalTitleEl.textContent = project.title;
  modalKickerEl.textContent = project.kicker;
  modalBodyEl.innerHTML = project.paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("");

  modalSecondaryMediaEl.innerHTML = secondaryMedia
    .map(
      (mediaPath, index) => `
        <div class="project-modal__secondary-image-wrap">
          <img
            class="project-modal__secondary-image"
            src="${mediaPath}"
            alt="${project.title} supporting image ${index + 2}"
            loading="lazy"
          />
        </div>
      `
    )
    .join("");
}

function openModal(section, projectIndex) {
  modalState.section = section;
  modalState.projectIndex = projectIndex;
  renderModal();

  modalEl.classList.add("is-open");
  document.body.classList.add("modal-open");
}

function closeModal() {
  modalEl.classList.remove("is-open");
  document.body.classList.remove("modal-open");
}

function animateProjectSwap(delta, updateCallback) {
  const targets = [modalImageEl, modalSecondaryMediaEl, modalTitleEl, modalKickerEl, modalBodyEl];
  const direction = delta >= 0 ? 1 : -1;
  const outX = -direction * 34;
  const inX = direction * 34;

  if (!targets.every((target) => target && typeof target.animate === "function")) {
    updateCallback();
    return Promise.resolve();
  }

  const fadeOut = targets.map((target) =>
    target
      .animate(
        [
          { opacity: 1, transform: "translateX(0)" },
          { opacity: 0, transform: `translateX(${outX}px)` },
        ],
        { duration: 140, easing: "cubic-bezier(0.4, 0, 1, 1)", fill: "forwards" }
      )
      .finished.catch(() => undefined)
  );

  return Promise.all(fadeOut).then(() => {
    updateCallback();

    targets.forEach((target) => {
      target.animate(
        [
          { opacity: 0, transform: `translateX(${inX}px)` },
          { opacity: 1, transform: "translateX(0)" },
        ],
        { duration: 220, easing: "cubic-bezier(0, 0, 0.2, 1)", fill: "both" }
      );
    });
  });
}

function stepProject(delta) {
  if (modalState.isSwitching) return;

  const list = portfolioData[modalState.section];
  const nextIndex = (modalState.projectIndex + delta + list.length) % list.length;

  modalState.isSwitching = true;
  animateProjectSwap(delta, () => {
    modalState.projectIndex = nextIndex;
    renderModal();
  }).finally(() => {
    modalState.isSwitching = false;
  });
}

function setupProjectEvents() {
  document.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-project-trigger='true']");
    if (trigger) {
      openModal(trigger.dataset.section, Number(trigger.dataset.index));
      return;
    }

    if (event.target.matches("[data-close-modal='true']")) {
      closeModal();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (!modalEl.classList.contains("is-open")) return;

    if (event.key === "Escape") closeModal();
    if (event.key === "ArrowLeft") stepProject(-1);
    if (event.key === "ArrowRight") stepProject(1);
  });

  document.addEventListener("keydown", (event) => {
    const trigger = event.target.closest("[data-project-trigger='true']");
    if (!trigger) return;
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openModal(trigger.dataset.section, Number(trigger.dataset.index));
    }
  });

  modalPrevEl.addEventListener("click", () => stepProject(-1));
  modalNextEl.addEventListener("click", () => stepProject(1));
  modalCloseEl.addEventListener("click", closeModal);
}

function setupScrollNav() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          topNavEl.classList.remove("is-visible");
        } else {
          topNavEl.classList.add("is-visible");
        }
      });
    },
    { threshold: 0.06 }
  );

  observer.observe(heroEl);
}

function setupMenuToggle() {
  if (!menuToggleEl || !siteNavEl) return;

  menuToggleEl.addEventListener("click", () => {
    const isOpen = siteNavEl.classList.toggle("is-open");
    menuToggleEl.setAttribute("aria-expanded", String(isOpen));
  });

  siteNavEl.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      siteNavEl.classList.remove("is-open");
      menuToggleEl.setAttribute("aria-expanded", "false");
    });
  });
}

function triggerIntroAnimation() {
  requestAnimationFrame(() => {
    document.body.classList.add("is-ready");
  });
}

renderCards();
setupSiteGate();
setupProjectEvents();
setupScrollNav();
setupMenuToggle();
triggerIntroAnimation();
